#!/usr/bin/env bash
# Check the documentation that lives in bitrl: every example that is built has
# a page that examples/examples.md links to, and Doxygen builds the example
# pages without warnings.
#
# The pages link to bitsim's classes and pages, so Doxygen reads bitsim's
# sources too. They come from BITSIM_SOURCE_DIR if it is set, and from a
# shallow clone of bitsim's master otherwise. Only warnings about bitrl's
# example pages fail the check; the API comments in include/ are not checked
# yet.
# Usage: [BITSIM_SOURCE_DIR=<bitsim checkout>] ci/check_docs.sh
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$root"

python3 ci/check_example_docs.py "$root"

out_dir="$(mktemp -d)"
trap 'rm -rf "$out_dir"' EXIT

bitsim="${BITSIM_SOURCE_DIR:-}"
if [ -z "$bitsim" ]; then
    bitsim="$out_dir/bitsim"
    git clone --quiet --depth 1 https://github.com/pockerman/bitsim.git "$bitsim"
fi
bitsim="$(cd "$bitsim" && pwd)"

# The same inputs as the documentation site, bitrl_cuberl_docs, uses
{
    echo "PROJECT_NAME = bitrl"
    echo "INPUT = include/bitrl examples $bitsim/src/bitsim $bitsim/examples $bitsim/doc"
    echo "RECURSIVE = YES"
    echo "FILE_PATTERNS = *.h *.hpp *.cpp *.md"
    echo "EXCLUDE = $bitsim/src/bitsim/extern"
    # Not built, see ci/check_example_docs.py
    echo "EXCLUDE_PATTERNS = */examples/cv/* */examples/example_5/* */examples/example_24/* */build/*"
    echo "EXAMPLE_PATH = examples $bitsim/examples"
    echo "EXAMPLE_RECURSIVE = YES"
    echo "IMAGE_PATH = examples $bitsim/examples"
    echo "OUTPUT_DIRECTORY = $out_dir/html"
    echo "EXTRACT_ALL = YES"
    echo "WARN_IF_UNDOCUMENTED = NO"
    echo "USE_MATHJAX = YES"
    # bitrl always builds with libtorch; bitsim_config.h, which defines the
    # BITSIM_ macros, is generated by CMake and is not in the input
    echo "PREDEFINED = USE_PYTORCH BITSIM_CHRONO BITSIM_IRRLICHT BITSIM_MQTT BITSIM_OPENCV BITSIM_LOG"
    echo "WARN_LOGFILE = $out_dir/warnings.log"
    echo "GENERATE_LATEX = NO"
    echo "HAVE_DOT = NO"
    echo "QUIET = YES"
} | doxygen - > /dev/null

if grep -E "^$root/examples/" "$out_dir/warnings.log"; then
    echo "error: fix the Doxygen warnings above"
    exit 1
fi
echo "Doxygen built the example pages without warnings"
